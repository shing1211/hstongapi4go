package push

import (
	"bytes"
	"testing"
)

func FuzzReadFrame(f *testing.F) {
	testcases := [][]byte{
		nil,
		{},
		{0},
		make([]byte, 150),
		make([]byte, 151),
		{0x00, 0x00},
		{0x48, 0x53, 0x00, 0x00},
		{0x48, 0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0xFF, 0xFF, 0xFF, 0xFF},
		{0x48, 0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		{0x48, 0x53, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
		{0x48, 0x53, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00},
	}
	for _, tc := range testcases {
		f.Add(tc)
	}

	f.Fuzz(func(t *testing.T, data []byte) {
		var rdr = bytes.NewReader(data)
		_, _, err := ReadFrame(rdr)
		if err == nil {
			return
		}
	})
}
